-- Table: public.spring_students

-- DROP TABLE IF EXISTS public.spring_students;

CREATE TABLE IF NOT EXISTS public.spring_students
(
    student_id integer NOT NULL GENERATED BY DEFAULT AS IDENTITY ( INCREMENT 1 START 1 MINVALUE 1 MAXVALUE 2147483647 CACHE 1 ),
    student_name character varying(255) COLLATE pg_catalog."default",
    student_course character varying(255) COLLATE pg_catalog."default",
    CONSTRAINT spring_students_pkey PRIMARY KEY (student_id)
)

TABLESPACE pg_default;

ALTER TABLE IF EXISTS public.spring_students
    OWNER to postgres;


-- Table: public.students

-- DROP TABLE IF EXISTS public.students;

CREATE TABLE IF NOT EXISTS public.students
(
    id integer NOT NULL,
    name character varying(100) COLLATE pg_catalog."default",
    course character varying(100) COLLATE pg_catalog."default",
    age integer,
    CONSTRAINT students_pkey PRIMARY KEY (id)
)

TABLESPACE pg_default;

ALTER TABLE IF EXISTS public.students
    OWNER to postgres;

REVOKE ALL ON TABLE public.students FROM student_app;

GRANT ALL ON TABLE public.students TO postgres;

GRANT DELETE, UPDATE, INSERT, SELECT ON TABLE public.students TO student_app;